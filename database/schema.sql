-- PortFlow target data model for Oracle Database 19c and later.
-- Run as the application schema owner. Re-runnable in a test schema: existing
-- PortFlow tables are dropped first. Never run this against production data.
-- The demo service uses the same tables on SQLite (service/portflow/schema_sqlite.sql).

BEGIN
  FOR t IN (SELECT table_name FROM user_tables
             WHERE table_name IN ('TERMINAL_EVENT', 'VEHICLE', 'SHIPMENT',
                                  'MESSAGE_ERROR', 'EDI_MESSAGE', 'PARTNER')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

CREATE TABLE partner (
  partner_id    VARCHAR2(10)  CONSTRAINT pk_partner PRIMARY KEY,
  name          VARCHAR2(100) NOT NULL,
  channel       VARCHAR2(4)   NOT NULL
                CONSTRAINT ck_partner_channel CHECK (channel IN ('REST', 'EDI', 'BOTH')),
  status        VARCHAR2(10)  NOT NULL
                CONSTRAINT ck_partner_status CHECK (status IN ('ONBOARDING', 'ACTIVE', 'SUSPENDED')),
  contact_email VARCHAR2(200),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE edi_message (
  message_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000)
                CONSTRAINT pk_edi_message PRIMARY KEY,
  partner_code  VARCHAR2(10),
  message_ref   VARCHAR2(35),
  channel       VARCHAR2(4)  NOT NULL
                CONSTRAINT ck_message_channel CHECK (channel IN ('REST', 'EDI')),
  status        VARCHAR2(10) NOT NULL
                CONSTRAINT ck_message_status CHECK (status IN ('ACCEPTED', 'REJECTED')),
  shipment_ref  VARCHAR2(35),
  vehicle_count NUMBER(5)    DEFAULT 0 NOT NULL,
  raw_payload   CLOB         NOT NULL,
  received_at   TIMESTAMP    NOT NULL,
  processed_at  TIMESTAMP    NOT NULL
);

-- Idempotency key: one row per (partner, message reference).
-- Oracle compares composite keys with one NULL column, so a plain UNIQUE
-- constraint would reject a second message that lacks a reference. The
-- function-based index only indexes rows that actually carry a reference.
CREATE UNIQUE INDEX uq_message_partner_ref ON edi_message (
  CASE WHEN message_ref IS NOT NULL THEN partner_code END,
  CASE WHEN message_ref IS NOT NULL THEN message_ref END
);
CREATE INDEX ix_message_status_received ON edi_message (status, received_at);
CREATE INDEX ix_message_received ON edi_message (received_at);

CREATE TABLE message_error (
  error_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000)
             CONSTRAINT pk_message_error PRIMARY KEY,
  message_id NUMBER NOT NULL CONSTRAINT fk_error_message REFERENCES edi_message (message_id),
  error_code VARCHAR2(30) NOT NULL,
  field_path VARCHAR2(100),
  detail     VARCHAR2(400)
);
CREATE INDEX ix_error_message ON message_error (message_id);

CREATE TABLE shipment (
  shipment_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000)
                   CONSTRAINT pk_shipment PRIMARY KEY,
  partner_id       VARCHAR2(10) NOT NULL CONSTRAINT fk_shipment_partner REFERENCES partner (partner_id),
  shipment_ref     VARCHAR2(35) NOT NULL,
  terminal_code    VARCHAR2(5)  NOT NULL,
  expected_arrival TIMESTAMP    NOT NULL,
  message_id       NUMBER       NOT NULL CONSTRAINT fk_shipment_message REFERENCES edi_message (message_id),
  created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_shipment_partner_ref UNIQUE (partner_id, shipment_ref)
);
CREATE INDEX ix_shipment_message ON shipment (message_id);
CREATE INDEX ix_shipment_expected ON shipment (expected_arrival);

CREATE TABLE vehicle (
  vehicle_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000)
              CONSTRAINT pk_vehicle PRIMARY KEY,
  shipment_id NUMBER       NOT NULL CONSTRAINT fk_vehicle_shipment REFERENCES shipment (shipment_id),
  vin         VARCHAR2(17) NOT NULL
              CONSTRAINT ck_vehicle_vin CHECK (REGEXP_LIKE(vin, '^[A-HJ-NPR-Z0-9]{17}$')),
  make        VARCHAR2(40),
  model       VARCHAR2(60),
  status      VARCHAR2(10) DEFAULT 'EXPECTED' NOT NULL
              CONSTRAINT ck_vehicle_status CHECK (status IN ('EXPECTED', 'ARRIVED')),
  arrived_at  TIMESTAMP,
  CONSTRAINT uq_vehicle_shipment_vin UNIQUE (shipment_id, vin)
);
CREATE INDEX ix_vehicle_vin ON vehicle (vin);

CREATE TABLE terminal_event (
  event_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000)
             CONSTRAINT pk_terminal_event PRIMARY KEY,
  vehicle_id NUMBER       NOT NULL CONSTRAINT fk_event_vehicle REFERENCES vehicle (vehicle_id),
  vin        VARCHAR2(17) NOT NULL,
  event_type VARCHAR2(20) NOT NULL CONSTRAINT ck_event_type CHECK (event_type IN ('ARRIVED')),
  event_time TIMESTAMP    NOT NULL,
  source     VARCHAR2(20) NOT NULL
);
CREATE INDEX ix_event_vehicle ON terminal_event (vehicle_id);

COMMENT ON TABLE partner IS 'Logistics partners allowed to announce vehicles, with their channel and onboarding status';
COMMENT ON TABLE edi_message IS 'Every inbound manifest (REST or EDI), accepted or rejected, with the raw payload for support';
COMMENT ON TABLE message_error IS 'Business rule violations per rejected message (codes in integrations/error-scenarios.md)';
COMMENT ON TABLE shipment IS 'Announced shipments, one per partner shipment reference';
COMMENT ON TABLE vehicle IS 'Vehicles expected at or arrived on the terminal, per shipment';
COMMENT ON TABLE terminal_event IS 'Physical events registered on the terminal (gate arrival)';

-- Reporting layer: the BI tool (WebFOCUS or similar) reads these views, never the base tables.

CREATE OR REPLACE VIEW v_partner_quality AS
SELECT m.partner_code,
       TRUNC(m.received_at) AS report_day,
       COUNT(*) AS messages,
       SUM(CASE WHEN m.status = 'REJECTED' THEN 1 ELSE 0 END) AS rejected,
       ROUND(100 * SUM(CASE WHEN m.status = 'REJECTED' THEN 1 ELSE 0 END) / COUNT(*), 1) AS rejection_pct,
       ROUND(AVG(EXTRACT(DAY FROM (m.processed_at - m.received_at)) * 86400
               + EXTRACT(HOUR FROM (m.processed_at - m.received_at)) * 3600
               + EXTRACT(MINUTE FROM (m.processed_at - m.received_at)) * 60
               + EXTRACT(SECOND FROM (m.processed_at - m.received_at))), 2) AS avg_processing_s
  FROM edi_message m
 GROUP BY m.partner_code, TRUNC(m.received_at);

CREATE OR REPLACE VIEW v_daily_arrivals AS
SELECT TRUNC(s.expected_arrival) AS arrival_day,
       s.partner_id,
       COUNT(v.vehicle_id) AS vehicles_expected,
       SUM(CASE WHEN v.status = 'ARRIVED' THEN 1 ELSE 0 END) AS vehicles_arrived,
       SUM(CASE WHEN v.status = 'EXPECTED' THEN 1 ELSE 0 END) AS vehicles_open
  FROM shipment s
  JOIN vehicle v ON v.shipment_id = s.shipment_id
 GROUP BY TRUNC(s.expected_arrival), s.partner_id;
